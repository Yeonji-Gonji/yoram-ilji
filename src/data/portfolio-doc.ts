/** 여정 단계. state = ok(정상) · warn(구현됐으나 잔여 검증) · gap(끊긴 곳) */
export interface JourneyStep {
  label: string;
  state?: 'ok' | 'warn' | 'gap';
  note?: string;
}

/** 이력서에는 담기지 않는 판단 근거. 무엇이 왜 막혀 있는지와 그 성격을 가른 표 */
export interface JudgementRow {
  subject: string;
  kind: string; // 결정 / 계약 / 검증 / 산출물 / 코드
  state: string;
}

export interface PortfolioDocCase {
  no: string; // 표지 목차 번호
  title: string; // 명사구 제목
  meta: string; // 기간 · 역할 · 팀 구성
  kind: string; // 자사 제품 / 공동사업 / 고객사 발주 / 개인 프로덕트
  summary: string; // 한 줄 요약 (서술형)
  problem: string[]; // 상황과 문제
  journey?: { label: string; steps: JourneyStep[] }; // 사용자 여정과 끊긴 지점
  work: { label: string; items: string[] }[]; // 한 일 (개조식)
  judgement?: { label: string; intro?: string; rows: JudgementRow[] }; // 판단 근거
  result: string[]; // 결과 (지표 우선)
  learned?: string; // 배운 점 1문장
  stack?: string;
  note?: string; // 정직한 한계
}

